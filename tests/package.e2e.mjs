import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cp, lstat, mkdtemp, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import test from 'node:test';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { project, artifacts, git, put } from './helpers.mjs';

test('a clean source pack installs without dev dependencies and serves CLI and MCP outside the checkout', { timeout: 120000 }, async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'prooflane-package-'));
  let client;
  t.after(async () => { await client?.close(); await rm(root, { recursive: true, force: true }); });
  const staging = join(root, 'source');
  const consumer = join(root, 'consumer');
  const target = join(root, 'target');
  const npm = (cwd, args) => {
    assert.ok(process.env.npm_execpath, 'Run this test through npm run test:package');
    const result = spawnSync(process.execPath, [process.env.npm_execpath, ...args], { cwd, encoding: 'utf8', timeout: 90000, maxBuffer: 8 * 1024 * 1024 });
    assert.equal(result.error, undefined);
    return result;
  };
  for (const file of ['src', 'skills', 'scripts', 'docs', 'README.md', 'package.json', 'package-lock.json', 'tsconfig.json']) await cp(join(project, file), join(staging, file), { recursive: true });
  await symlink(join(project, 'node_modules'), join(staging, 'node_modules'), 'junction');
  let result = npm(staging, ['pack', '--json', '--pack-destination', root]);
  await writeFile(join(artifacts, 'package-pack.json'), result.stdout);
  assert.equal(result.status, 0, result.stderr);
  const packed = JSON.parse(result.stdout)[0];
  await put(consumer, 'package.json', '{"private":true,"type":"module"}');
  result = npm(consumer, ['install', '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund', join(root, packed.filename)]);
  assert.equal(result.status, 0, result.stderr);
  const installed = join(consumer, 'node_modules/@sunnylost/prooflane');
  assert.equal((await lstat(installed)).isSymbolicLink(), false);
  assert.equal((await lstat(join(installed, 'dist/cli.js'))).isFile(), true);
  await assert.rejects(lstat(join(consumer, 'node_modules/typescript')), { code: 'ENOENT' });
  const skill = await readFile(join(installed, 'skills/prooflane/SKILL.md'), 'utf8');
  assert.match(skill, /check_changes/);
  await rm(staging, { recursive: true, force: true });
  await put(target, 'package.json', '{"private":true,"devDependencies":{"oxlint":"1.87.0"}}');
  await put(target, '.gitignore', 'node_modules/\n.prooflane/\n');
  await put(target, '.oxlintrc.json', '{"rules":{"no-debugger":"error"}}');
  await put(target, 'source.ts', 'debugger;\n');
  git(target, 'init', '-b', 'main'); git(target, 'add', '.'); git(target, 'commit', '-m', 'package fixture');
  result = npm(target, ['install', '--ignore-scripts', '--no-audit', '--no-fund']);
  assert.equal(result.status, 0, result.stderr);
  result = npm(consumer, ['exec', '--offline', '--', 'prooflane', 'verify', 'full', '--root', target, '--json']);
  assert.equal(result.status, 1, result.stderr);
  const blocked = JSON.parse(result.stdout);
  assert.equal(blocked.outcome, 'block');
  assert.ok(blocked.findings.some((f) => f.rule.includes('no-debugger')));
  client = new Client({ name: 'package-consumer', version: '1' });
  const transport = new StdioClientTransport({ command: process.execPath, args: [join(installed, 'dist/cli.js'), 'mcp', '--root', target] });
  await client.connect(transport);
  const evidence = await client.callTool({ name: 'explain', arguments: { runId: blocked.runId, findingId: blocked.findings[0].id } });
  assert.match(evidence.content[0].text, /debugger/);
  await put(target, 'source.ts', 'export const value = 1;\n');
  const reply = await client.callTool({ name: 'check_changes', arguments: {} });
  assert.equal(JSON.parse(reply.content[0].text).outcome, 'pass');
  await writeFile(join(artifacts, 'package-acceptance.json'), JSON.stringify({ node: process.version, platform: process.platform, integrity: packed.integrity, blocked, evidence, fixed: reply }, null, 2));
  await client.close();
  const performance = spawnSync(process.execPath, [join(installed, 'scripts/benchmark-performance.mjs'), target, '--tool-root', target, '--output-dir', join(artifacts, `installed-performance-${Date.now()}`), '--repetitions', '2'], { encoding: 'utf8', timeout: 60000 });
  assert.equal(performance.status, 0, performance.stdout + performance.stderr);
});
